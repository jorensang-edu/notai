function apiDevPlugin(): Plugin {
  return {
    name: 'api-dev-plugin',
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        const url = req.url || '';
        if (url.startsWith('/api/probar-correo')) {
          try {
            const { default: handler } = await server.ssrLoadModule('./api/probar-correo.ts');
            return await handler(req, res);
          } catch (err: any) {
            res.statusCode = 500;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ error: err.message || String(err) }));
            return;
          }
        }
        if (url.startsWith('/api/cron-reporte')) {
          try {
            const { default: handler } = await server.ssrLoadModule('./api/cron-reporte.ts');
            return await handler(req, res);
          } catch (err: any) {
            res.statusCode = 500;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ error: err.message || String(err) }));
            return;
          }
        }
        next();
      });
    },
  };
}

